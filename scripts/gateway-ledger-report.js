"use strict";

// What the BFF asked the web gateway, as a report.
//
// The gateway client tallies every call made through it (src/gatewayLedger.js): which of its functions, which
// gateway route, for a call or a bind which pair and whether a session the gateway holds was named, and for a
// read of one character whether that character was online on the BFF. `require("../src/eveGatewayClient")
// .gatewayLedger.rows()` gives the rows (`app.locals.gatewayLedger` is the same); a BFF started for a live check
// writes them to a JSON file. This turns such a file into docs/game-port-gateway-ledger.md: what still goes to
// the web gateway, set beside what the plan keeps there (docs/game-port-transport-plan.md, 2.3). The plan's
// cutover is done when a walk leaves nothing under `pilot`, `online` or `unlisted`.
//
//   node scripts/gateway-ledger-report.js <ledger.json> [what was done] [reportPath]

const fs = require("node:fs");
const path = require("node:path");
const { KINDS, kindOf } = require("../src/gatewayLedger");

/** What the cutover has to be rid of first, then what the plan keeps. */
const ORDER = ["pilot", "online", "unlisted", "unheld", "account", "chat"];
/** The kinds a finished cutover leaves no row of. */
const TO_GO = new Set(["pilot", "online", "unlisted"]);

/**
 * The calls as a pilot who is not logged in that the plan names (2.3): the structure directory's checks and
 * names, the corporation's reads in training, a member's offices for a fleet's delivery, a training pilot's
 * corporation fittings.
 */
const NAMED_SERVICES = new Set(["structureDirectory", "corpRegistry"]);
const NAMED_PAIRS = new Set(["officeManager.GetMyCorporationsOffices", "corpFittingMgr.GetFittings"]);
const namedInThePlan = (pair) => NAMED_PAIRS.has(pair) || NAMED_SERVICES.has(String(pair).split(".")[0]);

const cell = (value) => String(value ?? "").replace(/\|/g, "\\|");

function report(rows, { what = "", generatedOn = new Date().toISOString().slice(0, 10) } = {}) {
  const groups = new Map(ORDER.map((kind) => [kind, []]));
  for (const row of rows) groups.get(kindOf(row)).push(row);
  const calls = (list) => list.reduce((sum, row) => sum + row.calls, 0);
  const toGo = [...TO_GO].flatMap((kind) => groups.get(kind));
  const unnamed = groups.get("unheld").filter((row) => !namedInThePlan(row.pair));
  const plural = (count, word) => `${count} ${word}${count === 1 ? "" : "s"}`;
  const stands = [
    toGo.length > 0 ? `${plural(toGo.length, "row")} (${plural(calls(toGo), "call")}) under \`pilot\`, \`online\` or \`unlisted\`` : null,
    unnamed.length > 0 ? `${plural(unnamed.length, "pair")} asked as a pilot not logged in that the plan does not name` : null,
  ].filter((each) => each !== null);
  const lines = [
    "# What the BFF asks the web gateway",
    "",
    `Generated by \`scripts/gateway-ledger-report.js\` on ${generatedOn}${what ? `, from ${what}` : ""}. Do not edit by hand; make the walk again and run it.`,
    "",
    "Every call the BFF made on its gateway client, by the client's function and, for a call or a bind, by pair. " +
      "The tally is kept beneath the seam that sends a pilot to its transport (`src/gatewayLedger.js`), so a pilot on " +
      "the game port leaves no row of its own. Each row is set beside what the plan keeps on the gateway " +
      "(`docs/game-port-transport-plan.md`, 2.3).",
    "",
    "| Kind | Rows | Calls | Meaning |",
    "|---|---|---|---|",
    ...ORDER.map((kind) => `| ${kind} | ${groups.get(kind).length} | ${calls(groups.get(kind))} | ${KINDS[kind]} |`),
    `| **total** | **${rows.length}** | **${calls(rows)}** | |`,
    "",
    stands.length === 0
      ? "**Nothing here stands between this walk and the cutover:** no row is a held pilot's, a read of an online pilot, or a route the plan does not keep, and every call made as a pilot not logged in is one the plan names."
      : `**Still to go before the cutover is done: ${stands.join(", and ")}.**`,
    "",
  ];
  for (const kind of ORDER) {
    const list = groups.get(kind);
    if (list.length === 0) continue;
    lines.push(`## ${kind} (${list.length})`, "");
    if (kind === "unheld") {
      lines.push("| Function | Pair | Calls | Named in the plan |", "|---|---|---|---|");
      for (const row of list) lines.push(`| \`${cell(row.fn)}\` | \`${cell(row.pair)}\` | ${row.calls} | ${namedInThePlan(row.pair) ? "yes" : "**no**"} |`);
    } else if (kind === "pilot") {
      lines.push("| Function | Route | Pair | Calls |", "|---|---|---|---|");
      for (const row of list) lines.push(`| \`${cell(row.fn)}\` | \`${cell(row.route)}\` | ${row.pair ? `\`${cell(row.pair)}\`` : ""} | ${row.calls} |`);
    } else {
      lines.push("| Function | Route | The character | Calls |", "|---|---|---|---|");
      for (const row of list) {
        const who = row.online === true ? "online here" : row.online === false ? "not online here" : "";
        lines.push(`| \`${cell(row.fn)}\` | \`${cell(row.route)}\` | ${who} | ${row.calls} |`);
      }
    }
    lines.push("");
  }
  return `${lines.join("\n")}\n`;
}

if (require.main === module) {
  const [ledgerPath, what, reportPath = path.resolve(__dirname, "..", "docs", "game-port-gateway-ledger.md")] = process.argv.slice(2);
  if (!ledgerPath) {
    console.error("usage: node scripts/gateway-ledger-report.js <ledger.json> [what was done] [reportPath]");
    process.exit(2);
  }
  const rows = JSON.parse(fs.readFileSync(ledgerPath, "utf8"));
  fs.writeFileSync(reportPath, report(rows, { what }));
  console.log(`${rows.length} rows written to ${reportPath}`);
}

module.exports = { namedInThePlan, report };
